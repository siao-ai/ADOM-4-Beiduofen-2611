#!/usr/bin/env python3 -B
"""Generate ports/c/adom.c: one self-contained C99 file = generated tables + adom_core.c.

The model is read from models/ADOM-4-Beiduofen-2611.adom at build time (header inflated with zlib,
canonical Huffman codes computed here); nothing about the model is hard-coded in the C source.

    python3 -B ports/c/build.py [MODEL] && cc -O2 -std=c99 -o adom ports/c/adom.c
"""
import hashlib, os, sys, zlib
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "ports", "common"))
from gen_tables import build as unicode_tables

def varint(buf, p):
    n = sh = 0
    while True:
        b = buf[p]; p += 1; n |= (b & 0x7F) << sh; sh += 7
        if not b & 0x80: return n, p

def cstr(s):
    out = []
    for b in s.encode("utf-8"):
        if b in (0x22, 0x5C, 0x3F): out.append("\\" + chr(b))          # " \ ? (no trigraphs)
        elif 0x20 <= b < 0x7F: out.append(chr(b))
        else: out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'

def ints(xs, per=16):
    xs = list(xs)
    return ",\n".join("    " + ", ".join(str(x) for x in xs[i:i + per]) for i in range(0, len(xs), per)) or "    0"

def canonical(lengths):           # == adom/codec.py canonical(): order by (len, sym)
    items = sorted(lengths.items(), key=lambda x: (x[1], x[0]))
    code, prev, out = 0, None, []
    for s, l in items:
        code = 0 if prev is None else (code + 1) << (l - prev)
        out.append((s, code, l)); prev = l
    return out

def main():
    model = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "models", "ADOM-4-Beiduofen-2611.adom")
    buf = open(model, "rb").read()
    assert buf[:5] == b"ADOM4"
    p = 6; seed, p = varint(buf, p); m, p = varint(buf, p); n, p = varint(buf, p)
    lines = zlib.decompress(buf[p:p + n], -15).decode().split("\n"); p += n
    T = buf[p:p + (m + 7) // 8]
    syms = lines[0].split("\x1f")
    params = {k: int(v) for k, v in (x.split("=") for x in lines[1][1:].split(",") if x)}
    has_praise = len(lines) > 2 and lines[2].startswith("@")
    praise = [x for x in lines[2][1:].split("\x1f") if x] if has_praise else []
    ctxs = {}
    for l in lines[3 if has_praise else 2:]:
        c, rest = l.split("\x1e")
        ctxs[c] = {syms[int(a)]: int(b) for a, b in (x.split(":") for x in rest.split(","))}
    assert params.get("f") and "TEXT" in ctxs and praise, "model without text route/praise: port would need route 'none'"
    U = unicode_tables()

    o = []
    o.append("/* ===== generated by ports/c/build.py from %s (sha256 %s), CPython unicodedata %s ===== */"
             % (os.path.basename(model), hashlib.sha256(buf).hexdigest(), U["unidata"]))
    o.append("#include <stdint.h>\n#include <stddef.h>")
    o.append("#define ADOM_SEED %dULL\n#define ADOM_M %dULL\n#define ADOM_F %d\n#define ADOM_KMIN %d"
             % (seed, m, params.get("f", 0), params.get("Kmin", 6)))
    o.append("static const uint8_t ADOM_T[%d] = {\n%s\n};" % (len(T), ints(T, 24)))
    o.append("static const char *const ADOM_SYMS[%d] = {\n%s\n};" % (len(syms), ",\n".join("    " + cstr(s) for s in syms)))
    o.append("#define ADOM_NPRAISE %d\n#define ADOM_DEFAULT_PRAISE %s" % (len(praise), cstr("台灣很棒。")))
    o.append("static const char *const ADOM_PRAISE[%d] = {\n%s\n};" % (max(1, len(praise)), ",\n".join("    " + cstr(s) for s in praise) or '    ""'))
    o.append("typedef struct { uint32_t code; uint8_t len; uint16_t sym; } adom_code_t;")
    o.append("typedef struct { const char *name; int maxlen, count, first; } adom_ctx_t;")
    sidx = {s: i for i, s in enumerate(syms)}
    codes, ctab = [], []
    for c in sorted(ctxs):
        cc = canonical(ctxs[c])
        ctab.append("    { %s, %d, %d, %d }" % (cstr(c), max(l for _, _, l in cc), len(cc), len(codes)))
        codes += ["{%d,%d,%d}" % (code, l, sidx[s]) for s, code, l in cc]
    o.append("static const adom_code_t ADOM_CODES[%d] = {\n%s\n};" % (len(codes), ints(codes, 8)))
    o.append("#define ADOM_NCTX %d\nstatic const adom_ctx_t ADOM_CTX[%d] = {\n%s\n};" % (len(ctab), len(ctab), ",\n".join(ctab)))
    o.append("static const uint32_t ADOM_WS[%d] = {\n%s\n};" % (len(U["ws"]), ints(U["ws"])))
    o.append("static const uint32_t ADOM_WORD[%d][2] = {\n%s\n};" % (len(U["word"]), ints(("{%d,%d}" % (a, b) for a, b in U["word"]), 8)))
    keys = sorted(int(k) for k in U["nfkc"])
    pool, off = [], [0]
    for k in keys: pool += U["nfkc"][str(k)] if str(k) in U["nfkc"] else U["nfkc"][k]; off.append(len(pool))
    o.append("static const uint32_t ADOM_NFKC_KEY[%d] = {\n%s\n};" % (len(keys), ints(keys)))
    o.append("static const uint16_t ADOM_NFKC_OFF[%d] = {\n%s\n};" % (len(off), ints(off)))
    o.append("static const uint32_t ADOM_NFKC_POOL[%d] = {\n%s\n};" % (len(pool), ints(pool)))
    lk = sorted(int(k) for k in U["lower"])
    lv = [U["lower"][k] for k in lk]
    o.append("static const uint32_t ADOM_LOWER_KEY[%d] = { %s };" % (len(lk), ", ".join(map(str, lk))))
    o.append("static const uint32_t ADOM_LOWER_VAL[%d][4] = { %s };" % (len(lk), ", ".join("{%s}" % ",".join(map(str, v)) for v in lv)))
    o.append("static const uint8_t ADOM_LOWER_LEN[%d] = { %s };" % (len(lk), ", ".join(str(len(v)) for v in lv)))
    ci = [(ord(L), c) for L, cs in sorted(U["ci"].items()) for c in cs]
    o.append("static const uint32_t ADOM_CI[%d][2] = { %s };" % (len(ci), ", ".join("{%d,%d}" % x for x in ci)))
    o.append("/* ===== end of generated tables ===== */\n")
    core = open(os.path.join(HERE, "adom_core.c"), encoding="utf-8").read()
    out = os.path.join(HERE, "adom.c")
    open(out, "w", encoding="utf-8").write("\n".join(o) + "\n" + core)
    print("wrote %s (%d bytes)" % (out, os.path.getsize(out)))

if __name__ == "__main__":
    main()
