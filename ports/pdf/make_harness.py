#!/usr/bin/env python3 -B
"""Wrap the JavaScript *extracted from the PDF* into a self-contained ES5 test program that
simulates the minimal Acrobat object model (Doc.getField, Field.value/valueAsString, app.alert)
and presses the INFER button once per parity prompt.

    python3 -B ports/pdf/make_harness.py EXTRACTED_DIR OUT.js [--cr] [--limit N] [--set public|full]

--cr      deliver prompts the way Acrobat multiline text fields do: line breaks as "\\r"
The output program only needs a global print(); it runs under Duktape (ES5.1) or node's vm.
"""
import argparse, json, os
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))

STUB = r"""
// ---- minimal Acrobat object model ----------------------------------------------------------
var __alerts = [];
var app = { alert: function (m) { __alerts.push(String(m)); }, viewerType: "Harness", viewerVersion: 0 };
function __Field(name) { this.name = name; this._v = ""; }
__Field.prototype = {
  get value() {                       // Acrobat hands back a Number when the text looks numeric
    var v = this._v;
    return (v !== "" && /^\s*-?[0-9]+(\.[0-9]+)?\s*$/.test(v)) ? Number(v) : v;
  },
  set value(v) { this._v = String(v); },
  get valueAsString() { return this._v; }
};
var __doc = { _f: {}, getField: function (n) { if (!this._f[n]) this._f[n] = new __Field(n); return this._f[n]; } };
"""

RUNNER = r"""
// ---- press the button once per prompt -------------------------------------------------------
var __button = new Function(__BUTTON_SRC);
var __routes = {}, __bad = 0, __shown = 0, __t0 = new Date().getTime(), __i, __lim = Math.min(__P.length, __LIMIT);
for (__i = 0; __i < __lim; __i++) {
  __doc.getField("prompt").value = __CR ? __P[__i].replace(/\r\n|\n/g, "\r") : __P[__i];
  __doc.getField("answer").value = ""; __doc.getField("meta").value = "";
  __button.call(__doc);
  var __m = __doc.getField("meta").valueAsString, __e = __E[__i];
  var __route = (/route=([a-z]+)/.exec(__m) || [])[1], __hit = (/hit=(true|false)/.exec(__m) || [])[1];
  var __key = __m.indexOf("; key=") >= 0 ? __m.substring(__m.indexOf("; key=") + 6) : null;
  var __ok = __doc.getField("answer").valueAsString === __e.text && __route === __e.route &&
             __hit === String(__e.hit) && __key === String(__e.key);
  if (!__routes[__e.route]) __routes[__e.route] = [0, 0];
  __routes[__e.route][1]++; if (__ok) __routes[__e.route][0]++;
  if (!__ok) { __bad++; if (__shown++ < 5) print("MISMATCH #" + __i + " expected " + JSON.stringify(__e) + " got answer=" + JSON.stringify(__doc.getField("answer").valueAsString) + " meta=" + JSON.stringify(__m)); }
}
var __ms = new Date().getTime() - __t0, __r, __parts = [];
for (__r in __routes) __parts.push(__r + " " + __routes[__r][0] + "/" + __routes[__r][1]);
print("RESULT identical " + (__lim - __bad) + "/" + __lim + " (" + __parts.join(", ") + ") alerts=" + __alerts.length +
      " ms_per_prompt=" + (__ms / __lim).toFixed(3) + (__CR ? " [CR line breaks]" : ""));
"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("extracted"); ap.add_argument("out")
    ap.add_argument("--cr", action="store_true"); ap.add_argument("--limit", type=int, default=10**9)
    ap.add_argument("--set", default="public", help="public (tests/public, 17,288 prompts, default) or full (tests/, 6,715 prompts with exam text)")
    a = ap.parse_args()
    doc = open(os.path.join(a.extracted, "doclevel.js"), encoding="ascii").read()
    btn = open(os.path.join(a.extracted, "button.js"), encoding="ascii").read()
    d = os.path.join(ROOT, "tests", "public") if a.set == "public" else os.path.join(ROOT, "tests")
    P = json.load(open(os.path.join(d, "parity_prompts.json"), encoding="utf-8"))
    E = json.load(open(os.path.join(d, "parity_expected.json"), encoding="utf-8"))
    dump = lambda x: json.dumps(x, ensure_ascii=True, separators=(",", ":"))
    with open(a.out, "w", encoding="ascii") as f:
        f.write("// generated by ports/pdf/make_harness.py -- do not edit\n")
        f.write(doc + "\n" + STUB + "\n")
        f.write("var __BUTTON_SRC = " + dump(btn) + ";\n")
        # data as JSON text, parsed at run time: Duktape's compiler caps the number of literal
        # constants per function, and 17k prompts as array literals exceed it ("const limit")
        f.write("var __P = JSON.parse(" + dump(dump(P)) + ");\nvar __E = JSON.parse(" + dump(dump(E)) + ");\n")
        f.write("var __CR = %s, __LIMIT = %d;\n" % ("true" if a.cr else "false", a.limit))
        f.write(RUNNER)

if __name__ == "__main__":
    main()
