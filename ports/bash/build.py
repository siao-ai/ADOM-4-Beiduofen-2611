#!/usr/bin/env python3 -B
"""Generate ports/bash/adom.sh = generated model section + adom_core.bash.
The model is read from models/ at build time; the weights become one hex string."""
import hashlib, os, sys, unicodedata, zlib
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "ports", "common"))
from gen_tables import build as unicode_tables
sys.path.insert(0, os.path.join(ROOT, "ports", "c"))
from build import varint, canonical

def bq(s):                                    # bash $'...' quoting
    out = []
    for ch in s:
        o = ord(ch)
        if ch in "\\'": out.append("\\" + ch)
        elif o < 0x20 or o == 0x7F: out.append("\\x%02x" % o)
        else: out.append(ch)
    return "$'" + "".join(out) + "'"

def main():
    model = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "models", "ADOM-4-Beiduofen-2611.adom")
    buf = open(model, "rb").read()
    p = 6; seed, p = varint(buf, p); m, p = varint(buf, p); n, p = varint(buf, p)
    lines = zlib.decompress(buf[p:p + n], -15).decode().split("\n"); p += n
    T = buf[p:p + (m + 7) // 8]
    syms = lines[0].split("\x1f")
    params = {k: int(v) for k, v in (x.split("=") for x in lines[1][1:].split(",") if x)}
    has_praise = len(lines) > 2 and lines[2].startswith("@")
    praise = [x for x in lines[2][1:].split("\x1f") if x] if has_praise else []
    ctxs = {}
    for l in lines[3 if has_praise else 2:]:
        c, rest = l.split("\x1e")
        ctxs[c] = {syms[int(a)]: int(b) for a, b in (x.split(":") for x in rest.split(","))}
    assert params.get("f") and "TEXT" in ctxs and praise, "model without text route/praise: port would need route 'none'"
    U = unicode_tables()
    o = ["#!/usr/bin/env bash",
         "# ADOM-4-Beiduofen-2611 -- pure Bash inference (bash >= 3.2, no external commands).",
         "# generated by ports/bash/build.py from %s (sha256 %s)" % (os.path.basename(model), hashlib.sha256(buf).hexdigest()),
         "for _l in C.UTF-8 C.utf8 en_US.UTF-8 en_US.utf8; do LC_ALL=$_l; _t='台'; (( ${#_t} == 1 )) && break; done 2>/dev/null",
         "ADOM_SEED=%d ADOM_M=%d ADOM_F=%d" % (seed, m, params.get("f", 0)),
         "ADOM_W=" + T.hex()]
    names = {}
    for i, c in enumerate(sorted(ctxs)):
        cc = canonical(ctxs[c])
        var = "HUF_TEXT" if c == "TEXT" else "HUF_%d" % i
        names[c] = var
        o.append("%s=%s" % (var, bq(str(max(l for _, _, l in cc))
                                    + "".join("\x1f%d:%d=%s" % (l, code, s) for s, code, l in cc) + "\x1f")))
    o.append("ctx_var() { case $1 in %s *) CTX=;; esac; }" % " ".join("%s) CTX=%s;;" % (bq(c), v) for c, v in names.items()))
    o.append("PRAISE=(%s)" % " ".join(bq(s) for s in praise))
    # NFKC: one case arm per mapped code point, keyed by the decimal code point
    arms = ["%d) NFC=%s;;" % (k, bq("".join(map(chr, v)))) for k, v in sorted((int(k), v) for k, v in U["nfkc"].items())]
    o.append("nf_cp() { case $1 in %s *) return 1;; esac; }" % " ".join(arms))
    # \w ranges (Python re), for the (?![^\W]) lookahead after 填充A
    o.append("WORD_LO=(%s)" % " ".join(str(a) for a, b in U["word"]))
    o.append("WORD_HI=(%s)" % " ".join(str(b) for a, b in U["word"]))
    # prefilter: chars whose NFKC contains a character of an exam/TWV trigger word
    trig = set("學測科能力會考台臺灣價值補GSATgsatCP")
    src = sorted({chr(c) for c in (int(k) for k in U["nfkc"]) if trig & set(map(chr, U["nfkc"][str(c)] if str(c) in U["nfkc"] else U["nfkc"][c]))})
    o.append("trig_pre() { case $1 in *學測*|*學科能力*|*會考*|*台灣價值*|*臺灣價值*|*[Gg][Ss][Aa][Tt]*|*CAP*) return 0;; esac; "
             "[[ -n $TRIG_SRC ]] || return 1; local i; for ((i = 0; i < ${#TRIG_SRC}; i++)); do [[ $1 == *\"${TRIG_SRC:i:1}\"* ]] && return 0; done; return 1; }")
    o.append("TRIG_SRC=" + bq("".join(src)))
    core = open(os.path.join(HERE, "adom_core.bash"), encoding="utf-8").read()
    out = os.path.join(HERE, "adom.sh")
    open(out, "w", encoding="utf-8").write("\n".join(o) + "\n" + core)
    os.chmod(out, 0o755)
    print("wrote %s (%d bytes), %d NFKC arms, %d trigger-source chars" % (out, os.path.getsize(out), len(arms), len(src)))

if __name__ == "__main__":
    main()
